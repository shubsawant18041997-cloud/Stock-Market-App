// Tiny JSON-file store with one profile per app install (no accounts).
// Each phone generates a random profile id and sends it as `x-user-id`;
// watchlist, alert rules, history, push devices and email settings live
// inside that profile. Writes are atomic (tmp file + rename) and debounced.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import crypto from 'node:crypto';
import { config } from './config.js';

const file = config.dataFile instanceof URL ? fileURLToPath(config.dataFile) : config.dataFile;

const DEFAULT_WATCHLIST = [
  { market: 'US', symbol: 'AAPL', name: 'Apple Inc.' },
  { market: 'US', symbol: 'NVDA', name: 'NVIDIA Corporation' },
  { market: 'IN', symbol: 'RELIANCE.NS', name: 'Reliance Industries' },
  { market: 'IN', symbol: 'TCS.NS', name: 'Tata Consultancy Services' },
  { market: 'CRYPTO', symbol: 'BTC', name: 'Bitcoin' },
  { market: 'CRYPTO', symbol: 'ETH', name: 'Ethereum' },
];

const newProfile = () => ({
  watchlist: structuredClone(DEFAULT_WATCHLIST),
  rules: [],
  history: [],
  devices: [],
  settings: { email: '', emailEnabled: true, pushEnabled: true },
  createdAt: Date.now(),
  lastSeen: Date.now(),
});

const LEGACY = '__legacy__';

let data;
let saveTimer = null;

function load() {
  try {
    const raw = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (raw.users) {
      data = { users: {}, state: {}, ...raw };
    } else {
      // single-user file from before profiles existed: keep it so the first
      // phone that connects gets it back instead of a fresh default list
      const { state = {}, watchlist, rules, history, devices, settings } = raw;
      data = { users: {}, state };
      data.users[LEGACY] = { ...newProfile(), watchlist: watchlist || [], rules: rules || [], history: history || [], devices: devices || [], settings: { ...newProfile().settings, ...settings } };
      data.users[LEGACY].settings.email ||= config.alertEmail;
      console.log('[store] migrated single-user data; the first device to connect will claim it');
      flush();
    }
  } catch (e) {
    if (e.code !== 'ENOENT') console.error('[store] could not read db, starting fresh:', e.message);
    data = { users: {}, state: {} };
    flush();
  }
}

function flush() {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.tmp`;
  fs.writeFileSync(tmp, JSON.stringify(data, null, 2));
  fs.renameSync(tmp, file);
}

export function save() {
  clearTimeout(saveTimer);
  saveTimer = setTimeout(flush, 250);
}

export function saveNow() {
  clearTimeout(saveTimer);
  flush();
}

export const id = () => crypto.randomUUID();

export function db() {
  if (!data) load();
  return data;
}

/** Profile ids are generated by the app: 16–64 chars of letters, digits and dashes. */
export const validUserId = (uid) => typeof uid === 'string' && /^[A-Za-z0-9-]{16,64}$/.test(uid);

/** Get (or create) the profile for an id. Returns null if the server is full. */
export function user(uid) {
  const users = db().users;
  let u = users[uid];
  if (!u) {
    const count = Object.keys(users).filter((k) => k !== LEGACY).length;
    if (count >= config.maxUsers) return null;
    if (users[LEGACY]) {
      u = users[LEGACY];
      delete users[LEGACY];
      console.log(`[store] profile ${uid.slice(0, 8)}… claimed the migrated single-user data`);
    } else {
      u = newProfile();
    }
    users[uid] = u;
    save();
  }
  u.id = uid;
  if (Date.now() - (u.lastSeen || 0) > 60_000) {
    u.lastSeen = Date.now();
    save();
  }
  return u;
}

/** All real profiles (for the alert engine). */
export function allUsers() {
  return Object.entries(db().users)
    .filter(([k]) => k !== LEGACY)
    .map(([k, u]) => Object.assign(u, { id: k }));
}

process.on('exit', () => {
  if (saveTimer) flush();
});
